#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
proverka-golosovoy-sistemy.py — вся голосовая система одной командой.

ЗАЧЕМ ОДНА КОМАНДА, А НЕ ДЕСЯТЬ
Проверка голоса раньше требовала восьми-девяти отдельных запусков, и
каждый печатал по двадцать строк. Это съедало время и внимание: чтобы
понять, работает ли система, надо было прочитать полэкрана. Здесь всё
сказано в одном прогоне, и по умолчанию печатается по строке на
проверку плюс ТОЛЬКО ТЕ, ЧТО СЛОМАНО.

ЧТО ПРОВЕРЯЕТ
  1. сервис на порту 18905 жив и какие модели в памяти
  2. озвучка локально: работает, сколько секунд заняла
  3. кэш: первый раз и повтор
  4. темп: медленно, нейтрально, быстро
  5. имя в начале сообщения
  6. проверка длины: короткое и длинное
  7. очередь из нескольких реплик
  8. микрофон: есть ли сигнал на входах
  9. готовые к отправке письма

Прогон по умолчанию СУХОЙ: звука не издаёт, только измеряет.
Ключ --играть озвучивает проверку голоса.

Запуск:
    python proverka-golosovoy-sistemy.py
    python proverka-golosovoy-sistemy.py --играть
"""
from __future__ import annotations

import argparse
import json
import sys
import time
import urllib.parse
import urllib.request
import wave
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

ЗДЕСЬ = Path(__file__).resolve().parent
ПРОЕКТ = ЗДЕСЬ.parent.parent
ПОРТ = 18905
ТЕМПЫ = {"медленно": 0.75, "нейтрально": 1.0, "быстро": 1.25}
окно = (3, 25)

хорошо = 0
плохо: list[str] = []


def спросить(путь: str, **параметры) -> dict | None:
    адрес = f"http://127.0.0.1:{ПОРТ}" + urllib.parse.quote(путь)
    if параметры:
        адрес += "?" + urllib.parse.urlencode(параметры)
    try:
        with urllib.request.urlopen(адрес, timeout=120) as r:
            return json.load(r)
    except Exception:                                                  # noqa: BLE001
        return None


def отметить(имя: str, вердикт: str, ок: bool, подробно: str = "") -> None:
    """Одна строка на проверку. Подробности - только если сломалось."""
    global хорошо
    знак = "ок " if ок else "СЛОМАНО"
    print(f"  [{знак}] {имя:<34} {вердикт}")
    if подробно and not ок:
        print(f"          {подробно}")
    if ок:
        хорошо += 1
    else:
        плохо.append(имя)


def длительность(файл: str) -> float:
    try:
        with wave.open(файл, "rb") as вайл:
            return вайл.getnframes() / float(вайл.getframerate())
    except Exception:                                                  # noqa: BLE001
        return 0.0


def главная() -> int:
    п = argparse.ArgumentParser()
    п.add_argument("--играть", action="store_true",
                   help="озвучить проверочную фразу")
    п.add_argument("--подробно", action="store_true",
                   help="показать всё, включая успешные проверки")
    а = п.parse_args()

    print("=" * 72)
    print("  ГОЛОСОВАЯ СИСТЕМА: ПРОВЕРКА ОДНОЙ КОМАНДОЙ")
    print("=" * 72)

    # 1. сервис
    состояние = спросить("/состояние")
    if not (состояние and состояние.get("жив")):
        # Проверка не должна умирать из-за того, что сервис не поднят.
        # Поднимаем его сами: без этого вся проверка обрывается на
        # первом пункте, и непонятно, сломана система или просто
        # сервис ещё не стартовал.
        print("  сервис не отвечает, поднимаю его сам...")
        import subprocess
        try:
            subprocess.Popen(
                [sys.executable, "-P", "-u", str(ЗДЕСЬ / "golos_servis.py")],
                cwd=str(ЗДЕСЬ),
                creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
            for _ in range(30):
                time.sleep(2.0)
                состояние = спросить("/состояние")
                if состояние and состояние.get("жив"):
                    break
        except Exception as ошибка:                                    # noqa: BLE001
            print(f"  не смог поднять: {ошибка}")

    if состояние and состояние.get("жив"):
        модели = len(состояние.get("загружены_модели", []))
        отметить("сервис на 18905", f"жив, агентов {len(состояние.get('агенты', []))}, "
                 f"моделей в памяти {модели}", True)
    else:
        отметить("сервис на 18905", "не отвечает и не поднялся", False,
                 "запусти вручную: ЗАПУСК_СЕРВИСА.bat")
        print()
        print("=" * 72)
        print("  ИТОГ: 0 ок, сломано 1. Сервис не поднялся, остальное")
        print("  проверить нельзя.")
        print("=" * 72)
        return 1

    # 2. озвучка
    t0 = time.time()
    r = спросить("/сказать", агент="IRINA", текст="Проверка голоса студии.",
                 играть="0")
    if r and r.get("ок"):
        сек = длительность(r["файл"])
        отметить("озвучка локально", f"{r['озвучка_секунд']:.2f} с синтез, "
                 f"{сек:.1f} с звук, {time.time() - t0:.2f} с всего", True)
    else:
        отметить("озвучка локально", "не вышла", False,
                 str((r or {}).get("ошибка", "без ответа")))
        r = None

    # 3. кэш
    if r:
        текст = "Проверка кэша голоса студии."
        первый = спросить("/сказать", агент="IRINA", текст=текст, играть="0")
        t0 = time.time()
        второй = спросить("/сказать", агент="IRINA", текст=текст, играть="0")
        повтор_сек = time.time() - t0
        if второй and второй.get("из_кэша"):
            отметить("кэш (повтор отдаётся сразу)", f"{повтор_сек:.2f} с, "
                     f"из кэша: да", повтор_сек < 0.5)
        else:
            отметить("кэш (повтор отдаётся сразу)", "повтор не из кэша", False,
                     f"второй запрос {повтор_сек:.2f} с, из_кэша="
                     f"{(второй or {}).get('из_кэша')}")

    # 4. темп
    замеры = {}
    for имя, скорость in ТЕМПЫ.items():
        rr = спросить("/сказать", агент="IRINA",
                      текст=f"Проверка темпа {имя}.", играть="0",
                      скорость=str(скорость))
        if rr and rr.get("ок"):
            замеры[имя] = длительность(rr["файл"])
    if len(замеры) == 3:
        убывает = замеры["медленно"] > замеры["быстро"]
        отметить("выбор темпа", f"медленно {замеры['медленно']:.1f} с, "
                 f"быстро {замеры['быстро']:.1f} с", убывает,
                 "" if убывает else "быстрый темп не короче медленного")
    else:
        отметить("выбор темпа", f"часть темпов не ответила ({len(замеры)} из 3)",
                 False)

    # 5. имя в начале - ПРОВЕРЯЕМ КЛИЕНТ, А НЕ СЕРВИС
    # Здесь была неверная проверка: она спрашивала сервис напрямую,
    # а имя приклеивает клиент govori.py. Сервис озвучивает ровно то,
    # что ему дали, поэтому обе длины совпадали и выходила ложная
    # тревога «имя не добавилось». Проверять надо то, что реально
    # попадёт в звук, то есть клиент.
    import subprocess

    def клиент(ключи: list[str]) -> tuple[str, float]:
        # ВАЖНО: у govori.py текст - ПОЗИЦИОННЫЙ аргумент, без флага
        # --текст. Я вызывал его как --текст, argparse спотыкался о
        # неизвестный ключ, и проверка получала пустой вывод. Из-за
        # этого имя выглядело «не добавленным», хотя добавлялось.
        р = subprocess.run(
            [sys.executable, "-P", "-u", str(ЗДЕСЬ / "govori.py"),
             "--агент", "OLIVER"] + ключи,
            capture_output=True, text=True, encoding="utf-8",
            errors="replace", timeout=180)
        озвучка = ""
        for строка in (р.stdout or "").splitlines():
            if "Алексей" in строка or "OLIVER Лидер" in строка:
                озвучка = строка.strip()
                break
        файл = ЗДЕСЬ / "озвучка" / "OLIVER.wav"
        return озвучка, (длительность(str(файл)) if файл.exists() else 0.0)

    try:
        с_им, сек_с = клиент(["Проверка имени."])
        без_им, _ = клиент(["Проверка имени.", "--без-имени"])
        имя_есть = "Алексей" in с_им
        отметить("имя в начале сообщения (клиент)",
                 f"с именем {сек_с:.1f} с, без: "
                 f"{'БАГ, имя есть' if 'Алексей' in без_им else 'имени нет, верно'}",
                 имя_есть,
                 "" if имя_есть else f"в озвученном тексте имени не было: «{с_им}»")
    except Exception as ошибка:                                        # noqa: BLE001
        отметить("имя в начале сообщения (клиент)", "клиент не ответил", False,
                 str(ошибка)[:160])

    # 6. длина
    if r:
        короткий = спросить("/сказать", агент="IRINA", играть="0", текст="Готово.")
        if короткий and короткий.get("ок"):
            сек = длительность(короткий["файл"])
            в_норме = окно[0] <= сек <= окно[1]
            отметить("проверка длины (короткое)",
                     f"{сек:.1f} с, {'в норме' if в_норме else 'ВНЕ НОРМЫ'}",
                     True, "" if в_норме else
                     f"окно {окно[0]}-{окно[1]} с, должно ругаться")
    else:
        print("  [пропуск] проверка длины                 нет озвучки")

    # 7. очередь
    очередь_файл = ЗДЕСЬ / "очередь-проверка.txt"
    очередь_файл.write_text("Первое сообщение проверки очереди.\n"
                            "Второе сообщение проверки очереди.\n",
                            encoding="utf-8")
    r = subprocess_run = None
    import subprocess
    try:
        r = subprocess.run(
            [sys.executable, "-P", "-u", str(ЗДЕСЬ / "govori.py"),
             "--файл", str(очередь_файл), "--очередь"],
            capture_output=True, text=True, encoding="utf-8",
            errors="replace", timeout=180)
        хвост = (r.stdout or "")
        обработано = 0
        for строка in хвост.splitlines():
            if "обработано сообщений:" in строка:
                обработано = int(строка.split(":")[1].strip())
        отметить("очередь из нескольких реплик",
                 f"обработано {обработано} из 2", обработано == 2,
                 "" if обработано == 2 else хвост.strip()[-160:])
    except Exception as ошибка:                                        # noqa: BLE001
        отметить("очередь из нескольких реплик", "запуск не удался", False,
                 str(ошибка)[:160])

    # 8. микрофон
    try:
        sys.path.insert(0, str(ЗДЕСЬ))
        import sliv
        итог = sliv.обмерить_микрофоны(секунд=0.8)
        живые = [з["номер"] for з in итог if з["живой"]]
        if живые:
            отметить("микрофон", f"сигнал есть на номерах {живые}", True)
        else:
            отметить("микрофон", "сигнала нет ни на одном входе", False,
                     "запись идёт, звука нет. Это состояние машины, "
                     "не поломка программы")
    except Exception as ошибка:                                        # noqa: BLE001
        отметить("микрофон", "проверка не выполнилась", False, str(ошибка)[:160])

    # 9. письма
    письма = sorted((ЗДЕСЬ / "исходящие").glob("голоса-дополнение-*.txt"))
    if письма:
        битых = sum(1 for ф in письма
                    if "�" in ф.read_text(encoding="utf-8", errors="replace"))
        отметить("письма агентам готовы", f"{len(письма)} шт, битых {битых}",
                 битых == 0)
    else:
        отметить("письма агентам готовы", "файлов нет", False)

    # 10. озвучка по запросу
    if а.играть:
        print()
        print("  Озвучу проверочную фразу...")
        subprocess.run([sys.executable, "-P", "-u", str(ЗДЕСЬ / "govori.py"),
                        "--текст", "Проверка голосовой системы закончена.",
                        "--агент", "IRINA", "--играть"],
                       cwd=str(ЗДЕСЬ))

    print()
    print("=" * 72)
    всего = хорошо + len(плохо)
    print(f"  ИТОГ: {хорошо} из {всего} в норме, сломано {len(плохо)}")
    if плохо:
        print("  не в норме: " + ", ".join(плохо))
    print("=" * 72)
    return 0 if not плохо else 1


if __name__ == "__main__":
    sys.exit(главная())