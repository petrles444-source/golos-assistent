def коротко(текст: str, сколько: int = 200) -> str:
    """Первое предложение, не длиннее указанного числа знаков."""
    t = " ".join(текст.split())
    if len(t) <= сколько:
        return t
    конец = t.find(". ")
    if 40 <= конец <= сколько:
        return t[:конец + 1]
    return t[:сколько].rstrip() + "..."


