def с_имением(текст: str, агент: str) -> tuple[str, bool]:
    """Приклеивает имя в начало, если его там ещё нет.

    Правило владельца: голосовое сообщение начинается с имени. Иначе
    человек слышит сообщение и не понимает, кто к нему заговорил.
    Имя приклеивается один раз: если текст уже начинается с него,
    второй раз не добавляем.

    Здесь же снимается BOM - невидимый значок, который PowerShell
    пишет в начало файла. На слух он читается как «у» в начале фразы,
    и в очереди это выглядело как «﻿Поняла». Голос не должен
    читать то, чего в тексте нет.
    """
    текст = текст.lstrip("\ufeff").strip()
    имя = ИМЕНА.get(агент.upper(), агент.upper())
    начало = текст
    if начало.lower().startswith(имя.lower()) or \
       начало.lower().startswith(агент.lower()):
        return начало, False
    return f"{имя}. {начало}", True


def окно_длины(секунды: float, слов: int) -> str:
    """Честный вердикт по объёму: и по секундам, и по словам.

    Правило владельца: от 3 до 25 секунд, короткие тоже можно.
    Но если голос быстрый, одни секунды объём не показывают: за
    25 секунд быстрый голос успевает больше слов, чем медленный.
    Поэтому считаем и то, и другое, и говорим оба числа.
    """
    низкий, высокий = ОКНО_СЕКУНД
    части = []
    if секунды < низкий:
        части.append(f"КОРОЧЕ {низкий} с: {секунды:.1f} с")
    elif секунды > высокий:
        части.append(f"ДЛИННЕЕ {высокий} с: {секунды:.1f} с")
    else:
        части.append(f"длина в норме: {секунды:.1f} с")
    части.append(f"{слов} слов")
    if секунды >= низкий:
        # Речь по-русски примерно 2-2,5 слова в секунду. Меряем,
        # а не считаем «на глаз»: темп = слова / секунды.
        темп = слов / секунды if секунды else 0
        if темп < 1.5:
            части.append("темп медленный, за 25 секунд не уложишь много")
        elif темп > 3.2:
            части.append("темп быстрый, в 25 секунд влезет много слов")
        else:
            части.append(f"темп {темп:.1f} слова в секунду, обычный")
    вердикт = "; ".join(части)
    норма = низкий <= секунды <= высокий
    return ("НОРМА: " if норма else "ВНЕ НОРМЫ: ") + вердикт + \
           f" (окно {низкий}-{высокий} с)"


def играть(путь: Path) -> tuple[bool, str]:
    """MCI. winsound не берёт mp3, а edge-tts выдаёт mp3."""
    if not путь.exists():
        return False, "файла нет, играть нечего"
    мм = ctypes.WinDLL("winmm")
    буфер = ctypes.create_unicode_buffer(256)
    _счётчик = int(time.time() * 1000) % 100000
    имя = f"gv{_счётчик}"

    def команда(т: str) -> tuple[int, str]:
        return (int(мм.mciSendStringW(т, буфер, 256, None)), буфер.value)

    тип = "mpegvideo" if путь.suffix.lower() == ".mp3" else "waveaudio"
    код, _ = команда(f'open "{путь}" type {тип} alias {имя}')
    if код != 0:
        return False, f"плеер не открыл файл, код {код}"
    код, _ = команда(f"play {имя}")
    if код != 0:
        команда(f"close {имя}")
        return False, f"плеер не запустил, код {код}"
    # Считаем, сколько звука в файле, и ждём playback честно.
    # Раньше этого ожидания не было: команда play отдавалась, и программа
    # сразу выходила. Процесс умирал через 0,3 секунды, а вместе с ним
    # MCI и звук. Файл длился 7,3 секунды - слышно было меньше секунды,
    # голос обрывался.
    длительность = длительность_файла(путь)
    начало = time.time()
    ждали = 0.0
    while ждали < длительность + 3:
        time.sleep(0.15)
        ждали = time.time() - начало
        код, состояние = команда(f"status {имя} mode")
        if код != 0 or состояние.strip() != "playing":
            break
    команда(f"close {имя}")
    return True, (f"дослушано за {ждали:.1f} с, файл длится "
                  f"{длительность:.1f} с")


def длительность_файла(путь: Path) -> float:
    """Сколько секунд в файле, по его заголовку. Не наугад."""
    try:
        if путь.suffix.lower() == ".wav":
            import wave
            with wave.open(str(путь), "rb") as вайл:
                return вайл.getnframes() / float(вайл.getframerate())
        # Для mp3 точной подсчётки нет: берём размер и средний битрейт.
        return путь.stat().st_size / 8000.0
    except Exception:                                                  # noqa: BLE001
        return 3.0


def сервис_жив(таймаут: float = 6.0) -> bool:
    """Отвечает ли сервис. Проверка дешёвая, без синтеза."""
    try:
        адрес = "http://127.0.0.1:%d%s" % (ПОРТ, urllib.parse.quote("/состояние"))
        with urllib.request.urlopen(адрес, timeout=таймаут) as r:
            return bool(json.load(r).get("жив"))
    except Exception:                                                  # noqa: BLE001
        return False


def поднять_сервис(ждать: int = 45) -> bool:
    """Запускает сервис, если он не отвечает.

    Зачем. Раньше было так: сервис падал, озвучка тихо переходила на
    запасной путь и заново грузила модель - это двадцать секунд на
    каждое сообщение вместо полсекунды, и человек не понимал, почему
    так медленно. Теперь программа поднимает сервис сама и ждёт его.
    """
    import subprocess
    сценарий = ЗДЕСЬ / "golos_servis.py"
    if not сценарий.exists():
        return False
    try:
        subprocess.Popen(
            [sys.executable, "-P", "-u", str(сценарий)],
            cwd=str(ЗДЕСЬ),
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
    except Exception:                                                  # noqa: BLE001
        return False
    начало = time.time()
    while time.time() - начало < ждать:
        time.sleep(2.0)
        if сервис_жив(4.0):
            return True
    return False


def через_сервис(текст: str, агент: str, скорость: float = 1.0) -> dict | None:
    """Сервис на этой машине. Модель уже в памяти, отвечает быстро."""
    try:
        адрес = ("http://127.0.0.1:%d%s?%s" % (
            ПОРТ,
            urllib.parse.quote("/сказать"),
            urllib.parse.urlencode({"агент": агент, "текст": текст,
                                    "играть": "0",
                                    "скорость": f"{скорость:.3f}"})))
        with urllib.request.urlopen(адрес, timeout=90) as r:
            d = json.load(r)
        if not d.get("ок"):
            return None
        return {
            "ок": True,
            "движок": f"сервис {ПОРТ}, {d['движок']}",
            "файл": Path(d["файл"]),
            "байт": d["байт"],
            "секунд": d["озвучка_секунд"],
            "всего": d["всего_секунд"],
        }
    except Exception:                                                  # noqa: BLE001
        return None


def через_piper(текст: str, голос: str) -> dict:
    """Локально, без сети. Модель грузится заново, это минус секунды."""
    import wave
    папка = ЗДЕСЬ / "modeli"
    модель = папка / f"ru_RU-{голос}-medium.onnx"
    if not модель.exists():
        return {"ок": False, "ошибка": f"модели piper «{голос}» нет"}
    куда = ЗДЕСЬ / "озвучка_piper.wav"
    куда.unlink(missing_ok=True)
    t0 = time.time()
    try:
        from piper import PiperVoice
        движок = PiperVoice.load(str(модель))
        с_загрузкой = time.time() - t0
        t0 = time.time()
        with wave.open(str(куда), "wb") as вайл:
            движок.synthesize_wav(текст, вайл)
    except Exception as ошибка:                                        # noqa: BLE001
        return {"ок": False, "ошибка": f"{type(ошибка).__name__}: {ошибка}"}
    if куда.stat().st_size < 1000:
        return {"ок": False, "ошибка": "piper отдал пустой файл"}
    return {"ок": True, "движок": f"piper локально (модель {с_загрузкой:.0f} с)",
            "файл": куда, "байт": куда.stat().st_size,
            "секунд": round(time.time() - t0, 2),
            "всего": round(time.time() - (t0 - (time.time() - t0)) + с_загрузкой, 2)}


def через_edge(текст: str, голос: str, куда: Path) -> dict:
    """Microsoft Edge, бесплатно и без ключа. Нужен интернет."""
    import asyncio
    import edge_tts
    t0 = time.time()
    связь = edge_tts.Communicate(текст, голос)
    asyncio.run(связь.save(str(куда)))
    размер = куда.stat().st_size if куда.exists() else 0
    if размер < 1000:
        куда.unlink(missing_ok=True)
        return {"ок": False, "ошибка": f"edge-tts отдал пустой файл ({размер} Б)"}
    return {"ок": True, "движок": "edge-tts через сеть",
            "файл": куда, "байт": размер,
            "секунд": round(time.time() - t0, 2), "всего": round(time.time() - t0, 2)}


EDGE_ГОЛОСА = {"женский": "ru-RU-SvetlanaNeural", "мужской": "ru-RU-DmitryNeural"}


def озвучить(текст: str, выбор: str, агент: str, скорость: float = 1.0) -> dict:
    """Сервис, потом piper, потом сеть. Собирает, что получилось."""
    голос_piper = ГОЛОСА[выбор]
    неудачи = []

    if сервис_жив(5.0):
        r = через_сервис(текст, агент, скорость)
        if r:
            return r
        неудачи.append(f"сервис на {ПОРТ} не ответил на просьбу")
    else:
        # Сервиса нет. Раньше здесь был тихий переход на медленный путь,
        # и человек получал двадцать секунд ожидания без причины.
        # Теперь поднимаем сервис сами и говорим об этом.
        неудачи.append(f"сервис на {ПОРТ} не работал")
        if поднять_сервис():
            неудачи[-1] += ", поднял заново"
            r = через_сервис(текст, агент, скорость)
            if r:
                return r

    r = через_piper(текст, голос_piper)
    if r.get("ок"):
        r["неудачи"] = неудачи
        return r
    неудачи.append(f"piper: {r.get('ошибка')}")

    r = через_edge(текст, EDGE_ГОЛОСА[выбор], ЗДЕСЬ / "озвучка.mp3")
    if r.get("ок"):
        r["неудачи"] = неудачи
        return r
    неудачи.append(f"edge-tts: {r.get('ошибка')}")

    return {"ок": False, "ошибка": "Ни один движок не смог: " + "; ".join(неудачи)}


def очередь(строки: list[str], выбор: str, агент: str, играть_ли: bool,
            скорость: float = 1.0, темп_имя: str = "нейтрально",
            без_имени: bool = False) -> int:
    """Несколько сообщений подряд, каждое со своим именем и проверкой.

    Зачем. В разговоре коротких реплик несколько: «понял», «делаю»,
    «готово, смотри». Озвучивать их по одной командой неудобно, а
    одним длинным сообщением - читается как чужой монолог. Очередь
    даёт несколько коротких, по одной на реплику.
    """
    print(f"  ОЧЕРЕДЬ: {len(строки)} сообщени(й/я), голос {агент}, "
          f"темп {темп_имя}")
    print("=" * 66)
    всего = 0
    for номер, строка in enumerate(строки, 1):
        текст = " ".join(строка.split())
        if not текст:
            continue
        if not без_имени:
            текст, _ = с_имением(текст, агент)
        print(f"\n  [{номер}] {текст}")
        r = озвучить(текст, выбор, агент.upper(), скорость)
        if not r.get("ок"):
            print(f"      НЕ ВЫШЛО: {r.get('ошибка')}")
            всего += 1
            continue
        длительность = длительность_файла(r["файл"])
        print(f"      {r['движок']}, озвучка {r['секунд']} с")
        print(f"      {окно_длины(длительность, len(текст.split()))}")
        if играть_ли:
            ок, сообщение = играть(r["файл"])
            print(f"      {сообщение}")
        всего += 1
    print("\n" + "=" * 66)
    print(f"  обработано сообщений: {всего}")
    print("=" * 66)
    return 0


def прочитать_вход() -> str:
    if not sys.stdin.isatty():
        данные = sys.stdin.read().strip()
        if данные:
            return данные
    return ""


def главная() -> int:
    п = argparse.ArgumentParser(description="Озвучить короткий текст. Бесплатно, без ключа.")
    п.add_argument("текст", nargs="?", help="что сказать")
    п.add_argument("--файл", help="взять текст из файла")
    п.add_argument("--коротко", action="store_true", help="только первое предложение")
    п.add_argument("--максимум", type=int, default=200)
    п.add_argument("--голос", choices=list(ГОЛОСА), default=None,
                   help="пол голоса. По умолчанию берётся из карточки "
                        "агента, а не подставляется молча")
    п.add_argument("--агент", default="IRINA", help="чьим голосом")
    п.add_argument("--играть", action="store_true", help="озвучить, а не только создать файл")
    п.add_argument("--без-имени", action="store_true",
                   help="не начинать сообщение с имени")
    п.add_argument("--очередь", action="store_true",
                   help="каждая непустая строка - отдельное сообщение")
    п.add_argument("--темп", choices=list(ТЕМПЫ), default=None,
                   help="темп словами: медленно, нейтрально, быстро. "
                        "По умолчанию нейтрально")
    п.add_argument("--скорость", type=float, default=None,
                   help="точное число от 0,6 до 1,8, если нужно не круглое")
    а = п.parse_args()

    if а.файл:
        p = Path(а.файл)
        if not p.exists():
            print(f"  ФАЙЛА НЕТ: {p}")
            return 1
        текст = p.read_text(encoding="utf-8", errors="replace")
    elif а.текст:
        текст = а.текст
    else:
        текст = прочитать_вход()
        if not текст:
            print("  НЕЧЕГО ЧИТАТЬ. Скажи текст аргументом, --файл или через трубу.")
            return 1

    # Пол голоса. Раньше здесь стояло default="женский", и строка
    # «говорю голосом BASIL (женский)» печатала пол из чужого флага:
    # BASIL это Павел, голос у него мужской, dmitri. На звук это не
    # влияло, врала только надпись, но надпись в отчёте - это тоже
    # враньё. Теперь пол по умолчанию берётся из карточки агента, и
    # печатается только когда его задали руками.
    пол_задан = а.голос is not None
    if а.голос is None:
        а.голос = "женский"

    темп_число, темп_имя = разобрать_темп(а.темп, а.скорость)
    print(f"  темп: {темп_имя} (скорость {темп_число:.2f})")

    if а.очередь:
        строки = [с for с in текст.splitlines() if с.strip()]
        if not строки:
            print("  ОЧЕРЕДЬ ПУСТА: непустых строк нет")
            return 1
        return очередь(строки, а.голос, а.агент.upper(), а.играть,
                       темп_число, темп_имя, а.без_имени)

    if а.коротко or len(текст) > а.максимум:
        было = len(текст)
        текст = коротко(текст, а.максимум)
        print(f"  сокращено: {было} -> {len(текст)} знаков")

    # Правило владельца: голосовое сообщение начинается с имени.
    if not а.без_имени:
        текст, приклеено = с_имением(текст, а.агент)
        if приклеено:
            print(f"  в начало добавлено имя: "
                  f"{ИМЕНА.get(а.агент.upper(), а.агент)}")

    if пол_задан:
        print(f"  говорю голосом {а.агент} ({а.голос}, задан вручную):")
    else:
        print(f"  говорю голосом {а.агент} (пол из его карточки):")
    print(f"    {текст}")

    r = озвучить(текст, а.голос, а.агент.upper(), темп_число)
    for стр in r.get("неудачи", []):
        print(f"    сначала не вышло: {стр}")

    if not r.get("ок"):
        print(f"  НЕ ВЫШЛО: {r.get('ошибка')}")
        return 1

    # Длину меряем по получившемуся файлу, а не прикидываем по знакам.
    # Слова тоже считаем: если голос быстрый, в те же 25 секунд влезает
    # заметно больше слов, и по одним секундам объём не понять.
    длительность = длительность_файла(r["файл"])
    слов = len(текст.split())
    print(f"  движок: {r['движок']}")
    print(f"  озвучка заняла: {r['секунд']} с, всего {r['всего']} с, {r['байт']} Б")
    print(f"  {окно_длины(длительность, слов)}")

    if not а.играть:
        print("  СУХОЙ ПРОГОН: файл готов, не играла. Ключ --играть включает звук.")
        return 0

    ок, сообщение = играть(r["файл"])
    print(f"  ВОСПРОИЗВЕДЕНИЕ: {сообщение}")
    print("  Честно: файл отдан плееру. Услышал или нет - этого я не знаю.")
    return 0 if ок else 1


