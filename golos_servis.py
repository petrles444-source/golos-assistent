def главная() -> int:
    п = argparse.ArgumentParser()
    п.add_argument("--проверка", action="store_true")
    п.add_argument("--порт", type=int, default=ПОРТ)
    п.add_argument(
        "--сразу",
        action="store_true",
        help="загрузить все четыре голоса при старте. По умолчанию НЕ так")
    а = п.parse_args()

    if а.проверка:
        return проверить()

    print("=" * 64)
    print("  ГОЛОСОВОЙ СЕРВИС СТУДИИ")
    print("=" * 64)
    print(f"  порт: {а.порт}   только для этой машины")
    print(f"  модели: {ПАПКА_ГОЛОСОВ}")
    print(f"  выдача: {ПАПКА_ВЫДАЧИ}")
    print("  Модель грузится один раз и живёт в памяти. Остановить - Ctrl+C")
    print("=" * 64)

    сервер = ThreadingHTTPServer(("127.0.0.1", а.порт), Обработчик)

    # ГОЛОСА ГРУЗЯТСЯ ПО ПЕРВОМУ ОБРАЩЕНИЮ. РЕШЕНИЕ ВЛАДЕЛЬЦА.
    #
    # Я предлагала загружать сразу и предупреждала, что ленивая выйдет
    # дороже. Замер подтвердил предупреждение, и всё же выбрали ленивую.
    # Значит, цифры оставляю тут, чтобы решение не выглядело ошибкой:
    #
    # Замерено честно, оба режима озвучили одни и те же четыре фразы,
    # оба держали все четыре модели:
    #   ленивая: 819,3 МБ приват, 662,9 МБ рабочий, 32 потока
    #   сразу:   359,2 МБ приват, 371,0 МБ рабочий, 35 потоков
    # Ленивая выигрывает только пока сервис молчит: 17 МБ против 359.
    # Почему при загруженных голосах она тяжелее - не выяснено,
    # помечено как гипотеза: по-разному ведут себя площадки памяти
    # onnxruntime при последовательной и при параллельной загрузке.
    #
    # Что покупается и что платится:
    #   выигрыш - 342 МБ, пока никто не говорил;
    #   плата   - 460 МБ, когда заговорили все четыре голоса;
    #   плата   - 4 секунды на первое обращение к новому голосу.
    #
    # Вернуть загрузку сразу можно флагом --сразу.
    if а.сразу:
        for имя in ("irina", "denis", "dmitri", "ruslan"):
            threading.Thread(target=модель, args=(имя,), daemon=True).start()
        print("  гружу четыре голоса в фоне, сервис уже отвечает", flush=True)
    else:
        print("  голоса грузятся по первому обращению, "
              "первый раз около 4 секунд", flush=True)
    try:
        сервер.serve_forever()
    except KeyboardInterrupt:
        print("\n  остановлено")
    finally:
        сервер.server_close()
    return 0


if __name__ == "__main__":
    sys.exit(главная())